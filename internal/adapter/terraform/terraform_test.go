func analyze(t *testing.T, c config.Config, files map[string]string) *facts.Analysis {
	t.Helper()
	tree := fstest.MapFS{}
	var paths []string
	for p, src := range files {
		tree[p] = &fstest.MapFile{Data: []byte(src)}
		if (terraform.Adapter{}).Claims(p) {
			paths = append(paths, p)
		}
	}
	sort.Strings(paths)
	a, err := terraform.Adapter{}.Analyze(engine.Version{FS: tree}, c, paths)
	if err != nil {
		t.Fatal(err)
	}
	return a
}

// viewpoint: behaviour
// target: terraform.Adapter.Claims
// Terraform's configuration, its test files and its variable files are Terraform's; other HCL and
// YAML are not.
func TestTerraformClaimsItsFiles(t *testing.T) {
	for p, want := range map[string]bool{
		"main.tf": true, "modules/network/variables.tf": true, "tests/main.tftest.hcl": true, "prod.tfvars": true,
		"main.tf.json": false, "packer.pkr.hcl": false, "site.yml": false, "main.go": false,
	} {
		got := terraform.Adapter{}.Claims(p)
		if got != want {
			t.Errorf("Claims(%s) = %v, want %v", p, got, want)
		}
	}
}

// viewpoint: behaviour
// target: terraform.Adapter.Analyze
// Each file has its role and its module's directory as its unit; a file HCL cannot parse is unread
// and gives nothing else; a variables file is other.
func TestTerraformFilesAndRoles(t *testing.T) {
	a := analyze(t, config.Config{GeneratedFiles: []string{"gen/**"}}, map[string]string{
		"main.tf":                      "variable \"region\" {}\n",
		"modules/network/main.tf":      "output \"id\" {\n  value = 1\n}\n",
		"modules/network/broken.tf":    "variable \"x\" {\n",
		"tests/main.tftest.hcl":        "run \"plan\" {\n  command = plan\n}\n",
		"prod.tfvars":                  "region = \"eu\"\n",
		"gen/main.tf":                  "variable \"generated\" {}\n",
		"modules/network/generated.tf": "# Code generated by a tool. DO NOT EDIT.\nvariable \"too\" {}\n",
	})
	var got []string
	for _, f := range a.Files {
		got = append(got, fmt.Sprintf("%s %s %s unit=%s path=%s unread=%v lines=%d", f.Path, f.Language, f.Role, f.Unit, f.UnitPath, f.Unread, f.Lines))
	}
	want := []string{
		"gen/main.tf terraform generated unit=gen path=gen unread=false lines=2",
		"main.tf terraform source unit=. path=. unread=false lines=2",
		"modules/network/broken.tf terraform other unit= path= unread=true lines=2",
		"modules/network/generated.tf terraform generated unit=modules/network path=modules/network unread=false lines=3",
		"modules/network/main.tf terraform source unit=modules/network path=modules/network unread=false lines=4",
		"prod.tfvars terraform other unit= path= unread=false lines=2",
		"tests/main.tftest.hcl terraform test unit=tests path=tests unread=false lines=4",
	}
	if !slices.Equal(got, want) {
		t.Errorf("files:\n got %q\nwant %q", got, want)
	}
	var ids []string
	for _, s := range a.Symbols {
		ids = append(ids, s.ID)
	}
	if want := []string{"..var.region", "modules/network.output.id"}; !slices.Equal(ids, want) {
		t.Errorf("symbols of source files: got %v, want %v", ids, want)
	}
}

// viewpoint: behaviour
// target: terraform.Adapter.Analyze
// Variables and outputs are the module's symbols: always exported, of kind value, and documented
// only by a description that says something.
func TestTerraformVariablesAndOutputsAreValues(t *testing.T) {
	a := analyze(t, config.Config{}, map[string]string{"modules/network/main.tf": `variable "region" {
  description = "Where the network is."
  type        = string
}

variable "cidr" {
  description = ""
}

output "region" {
  value = var.region
}

resource "aws_vpc" "main" {}
locals {
  name = "a"
}
`})
	var got []string
	for _, s := range a.Symbols {
		got = append(got, fmt.Sprintf("%s %s %d-%d exported=%v doc=%v", s.ID, s.Kind, s.Line, s.EndLine, s.Exported, s.Doc))
	}
	want := []string{
		"modules/network.output.region value 10-12 exported=true doc=false",
		"modules/network.var.cidr value 6-8 exported=true doc=false",
		"modules/network.var.region value 1-4 exported=true doc=true",
	}
	sort.Strings(got)
	if !slices.Equal(got, want) {
		t.Errorf("symbols:\n got %q\nwant %q", got, want)
	}
}

// viewpoint: behaviour
// target: terraform.Adapter.Analyze
// Module sources and required providers are imports. A relative source is internal and resolves to
// its directory; any other is named by its address without the version query and subdirectory.
// Providers perform input and output, and so do modules configuration lists in rules.tests.io.
func TestTerraformImports(t *testing.T) {
	a := analyze(t, config.Config{IO: []string{"hashicorp/consul"}}, map[string]string{"envs/prod/main.tf": `terraform {
  required_providers {
    aws = {
      source  = "hashicorp/aws"
      version = "~> 5.0"
    }
    old = "~> 1.0"
  }
}

module "network" {
  source = "../../modules/network"
}

module "consul" {
  source = "hashicorp/consul/aws//modules/consul-cluster"
}

module "queue" {
  source = "git::https://example.com/infra.git//worker/queue?ref=v1.2.0"
}
`})
	var got []string
	for _, im := range a.Imports {
		got = append(got, fmt.Sprintf("%d %s -> %s internal=%v io=%v", im.Line, im.FromUnit, im.ToUnit, im.Internal, im.IO))
	}
	want := []string{
		"4 envs/prod -> hashicorp/aws internal=false io=true",
		"12 envs/prod -> modules/network internal=true io=false",
		"16 envs/prod -> hashicorp/consul/aws internal=false io=true",
		"20 envs/prod -> git::https://example.com/infra.git internal=false io=false",
	}
	if !slices.Equal(got, want) {
		t.Errorf("imports:\n got %q\nwant %q", got, want)
	}
}

const testFile = `mock_provider "aws" {}

variables {
  region = "eu-west-1"
}

# Plans the network with a small range.
# guards: network-cidr
run "small_range" {
  variables {
    cidr = "10.0.0.0/24"
  }

  assert {
    condition     = output.id != "" && length(output.subnets) == 2
    error_message = "no network"
  }
  assert {
    condition     = output.id == output.id
    error_message = "unstable"
  }
}

run "rejects_bad_cidr" {
  module {
    source = "./modules/network"
  }
  override_resource {
    target = aws_vpc.main
  }
  variables {
    cidr = "nope"
  }
  expect_failures = [var.cidr]
}
`

// viewpoint: behaviour
// target: terraform.Adapter.Analyze
// Each run block is a test: its assert blocks and expect_failures are its asserts, the variables it
// passes and the outputs its conditions read are its calls into the module it tests, and mocks are
// hazards, including the ones written for the whole file.
func TestTerraformRunBlocksAreTests(t *testing.T) {
	a := analyze(t, config.Config{}, map[string]string{"tests/network.tftest.hcl": testFile})
	if len(a.Tests) != 2 {
		t.Fatalf("got %d tests, want 2", len(a.Tests))
	}
	small, bad := a.Tests[0], a.Tests[1]
	type summary struct {
		name    string
		line    int
		asserts int
		calls   []string
		hazards []string
	}
	sum := func(tt facts.Test) summary {
		s := summary{name: tt.Name, line: tt.Line, asserts: tt.Asserts}
		for _, c := range tt.Calls {
			s.calls = append(s.calls, fmt.Sprintf("%s x%d", c.Target, c.Times))
		}
		for _, h := range tt.Hazards {
			s.hazards = append(s.hazards, fmt.Sprintf("%s %d %s", h.Category, h.Line, h.Evidence))
		}
		return s
	}
	wantSmall := summary{name: "small_range", line: 9, asserts: 2,
		calls:   []string{"..output.id x3", "..output.subnets x1", "..var.cidr x1", "..var.region x1"},
		hazards: []string{`mock 1 mock_provider "aws"`}}
	wantBad := summary{name: "rejects_bad_cidr", line: 24, asserts: 1,
		calls:   []string{"modules/network.var.cidr x1", "modules/network.var.region x1"},
		hazards: []string{`mock 1 mock_provider "aws"`, "mock 28 override_resource target = aws_vpc.main"}}
	for _, c := range []struct{ got, want summary }{{sum(small), wantSmall}, {sum(bad), wantBad}} {
		if fmt.Sprint(c.got) != fmt.Sprint(c.want) {
			t.Errorf("test:\n got %+v\nwant %+v", c.got, c.want)
		}
	}
	if got := small.Declared["guards"]; !slices.Equal(got, []string{"network-cidr"}) {
		t.Errorf("declared guards = %v, want [network-cidr]", got)
	}
	if bad.Declared != nil {
		t.Errorf("a run block with no comment above it declared %v", bad.Declared)
	}
}

// viewpoint: invariant
// target: terraform.Adapter.Analyze
// Adapters design invariant 6: a run block's fingerprint ignores its name, comments and layout, and
// changes with any literal.
func TestTerraformRunFingerprint(t *testing.T) {
	body := func(src string) string {
		a := analyze(t, config.Config{}, map[string]string{"main.tftest.hcl": src})
		if len(a.Tests) != 1 || a.Tests[0].Body == "" {
			t.Fatalf("no fingerprint from %q", src)
		}
		return a.Tests[0].Body
	}
	base := body("run \"a\" {\n  variables {\n    cidr = \"10.0.0.0/24\"\n  }\n}\n")
	same := body("# a comment\nrun \"b\" {\n  variables { # another\n    cidr   =   \"10.0.0.0/24\"\n\n  }\n}\n")
	other := body("run \"a\" {\n  variables {\n    cidr = \"10.0.0.0/16\"\n  }\n}\n")
	if base != same {
		t.Error("renaming, commenting or re-laying out a run block changed its fingerprint")
	}
	if base == other {
		t.Error("changing a literal kept the fingerprint")
	}
}

// viewpoint: behaviour
// target: terraform.Adapter.Analyze
// All three comment forms are comments, without their delimiters; tflint, checkov and trivy
// instructions are directives, and an exception marker stays an ordinary comment for the engine.
func TestTerraformComments(t *testing.T) {
	a := analyze(t, config.Config{}, map[string]string{"main.tf": `# tflint-ignore: terraform_unused_declarations
variable "a" {}
// gate:allow comments/missing-doc the module is internal
variable "b" {}
/* a block
   comment */
#checkov:skip=CKV_AWS_20:public by design
#trivy:ignore:AVD-AWS-0086
variable "c" {} # trailing
`})
	var got []string
	for _, c := range a.Comments {
		got = append(got, fmt.Sprintf("%d %q directive=%v", c.Line, c.Text, c.Directive))
	}
	want := []string{
		`1 "tflint-ignore: terraform_unused_declarations" directive=true`,
		`3 "gate:allow comments/missing-doc the module is internal" directive=false`,
		"5 \"a block\\n   comment\" directive=false",
		`7 "checkov:skip=CKV_AWS_20:public by design" directive=true`,
		`8 "trivy:ignore:AVD-AWS-0086" directive=true`,
		`9 "trailing" directive=false`,
	}
	if !slices.Equal(got, want) {
		t.Errorf("comments:\n got %q\nwant %q", got, want)
	}
}
