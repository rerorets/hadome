#!/bin/sh
# Regenerates the Go parsers of the SQL dialects from the grammars in each directory's src/.
#
# Each directory is one dialect's grammar: src/*.g4 are the ANTLR grammars, src/*.go.in the support
# code the grammar's actions call, LICENSE the grammar's license. This script writes every .go file
# of the directory, all marked as generated; nothing else is edited by hand.
#
# Needs Java 11 or later and the ANTLR tool of the version the Go runtime in go.mod has:
#   ANTLR_JAR=/path/to/antlr-4.13.1-complete.jar internal/adapter/sql/grammar/generate.sh [dialect...]
# Without dialects, every directory is generated.
# docs/maintaining/sql-grammars.md says where the jar and the grammars come from.
set -eu

: "${ANTLR_JAR:?set ANTLR_JAR to antlr-4.13.1-complete.jar}"
here=$(cd "$(dirname "$0")" && pwd)

if [ $# -eq 0 ]; then
	set -- "$here"/*/
fi
for arg in "$@"; do
	dir="$here/$(basename "$arg")/"
	pkg=$(basename "$dir")
	rm -f "$dir"*.go
	tmp=$(mktemp -d)
	cp "$dir"src/*.g4 "$tmp"/
	(
		cd "$tmp"
		for g in *Lexer.g4 *Parser.g4; do
			java -jar "$ANTLR_JAR" -Dlanguage=Go -package "$pkg" -no-listener -no-visitor -Xexact-output-dir -o . "$g"
		done
	)
	for f in "$tmp"/*.go; do
		cp "$f" "$dir$(basename "$f" | tr 'A-Z' 'a-z')"
	done
	for f in "$dir"src/*.go.in; do
		[ -e "$f" ] || continue
		out="$dir$(basename "$f" .go.in | tr 'A-Z' 'a-z')_support.go"
		{
			echo "// Code generated by generate.sh from src/$(basename "$f"). DO NOT EDIT."
			echo
			sed "s/^package parser$/package $pkg/" "$f"
		} >"$out"
	done
	rm -rf "$tmp"
	# ANTLR ends every rule with an unreachable "goto errorExit" so that the label is always used,
	# which go vet reports. The goto moves to right before the label, where it is reachable.
	perl -0pi -e 's/\n\tgoto errorExit \/\/ Trick to prevent compiler error if the label is not used\n/\n/g; s/\nerrorExit:\n/\n\tgoto errorExit\nerrorExit:\n/g' "$dir"*.go
	gofmt -w "$dir"*.go
done
