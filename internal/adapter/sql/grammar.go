package sql

import (
	"fmt"

	"github.com/antlr4-go/antlr/v4"
)

// Grammar reads the syntax of one dialect.
type Grammar interface {
	// Parse reads text, which starts at byte offset base and line line of its file, into a tree
	// whose offsets and lines are the file's. It fails on the first syntax error: a statement it
	// cannot read may be the one that drops or renames an object.
	Parse(text string, base, line int) (*Node, error)
}

// grammars are the grammars this build has, by dialect name. Each dialect's grammar_<name>.go adds
// its own; only enabled dialects' grammars are in a build without -tags sqlgrammars, so that the
// parsers of dialects nobody can choose are not linked in.
var grammars = map[string]Grammar{}

// antlrGrammar is a Grammar generated by ANTLR from a public grammar (grammar/).
type antlrGrammar struct {
	lexer  func(antlr.CharStream) antlr.Lexer
	parser func(antlr.TokenStream) antlr.Parser
	// entry runs the start rule that reads a whole script.
	entry func(antlr.Parser) antlr.ParseTree
	// inlined maps a rule to the rule of a lone child that is replaced by its own children. A grammar
	// changed so that SLL reads a construct may read it one rule deeper; this gives the tree the
	// original grammar gives.
	inlined map[string]string
}

// syntaxError keeps the first error the lexer or the parser reports.
type syntaxError struct {
	*antlr.DefaultErrorListener
	err error
}

// gate:allow size/params reason: ANTLR's ErrorListener interface fixes these six parameters
func (e *syntaxError) SyntaxError(_ antlr.Recognizer, offending interface{}, line, col int, msg string, _ antlr.RecognitionException) {
	if tok, ok := offending.(antlr.Token); ok && msg == "" {
		msg = fmt.Sprintf("unexpected %q", tok.GetText())
	}
	if e.err == nil {
		e.err = fmt.Errorf("line %d:%d: %s", line, col, msg)
	}
}

// Parse reads text in two passes, as ANTLR recommends: the fast SLL prediction first, and the full
// LL prediction only when SLL fails. SLL may fail on input LL reads, never the other way round, so
// the result is the same as LL alone.
func (g antlrGrammar) Parse(text string, base, line int) (*Node, error) {
	tree, p, err := g.run(text, antlr.PredictionModeSLL)
	if err != nil {
		tree, p, err = g.run(text, antlr.PredictionModeLL)
	}
	if err != nil {
		return nil, shiftError(err, line)
	}
	c := converter{rules: p.GetRuleNames(), symbols: p.GetSymbolicNames(),
		bytes: runeOffsets(text), base: base, line: line - 1, inlined: g.inlined}
	return c.node(tree, nil), nil
}

func (g antlrGrammar) run(text string, mode int) (antlr.ParseTree, antlr.Parser, error) {
	errs := &syntaxError{DefaultErrorListener: antlr.NewDefaultErrorListener()}
	lx := g.lexer(antlr.NewInputStream(text))
	lx.RemoveErrorListeners()
	lx.AddErrorListener(errs)
	p := g.parser(antlr.NewCommonTokenStream(lx, antlr.TokenDefaultChannel))
	p.RemoveErrorListeners()
	p.AddErrorListener(errs)
	p.GetInterpreter().SetPredictionMode(mode)
	p.SetErrorHandler(quietStrategy{antlr.NewDefaultErrorStrategy()})
	tree, err := runEntry(g.entry, p)
	if err == nil {
		err = errs.err
	}
	return tree, p, err
}

// quietStrategy is ANTLR's default strategy, except that it reports every error to the listeners.
// The default prints some kinds of error to standard output, which would mix with hadome's output.
type quietStrategy struct{ *antlr.DefaultErrorStrategy }

func (quietStrategy) ReportError(p antlr.Parser, e antlr.RecognitionException) {
	p.NotifyErrorListeners(e.GetMessage(), e.GetOffendingToken(), e)
}

// runEntry runs the start rule. The generated parsers panic on some input their actions cannot
// handle; that is a syntax error of the file, not a failure of hadome.
func runEntry(entry func(antlr.Parser) antlr.ParseTree, p antlr.Parser) (tree antlr.ParseTree, err error) {
	defer func() {
		if r := recover(); r != nil {
			tok := p.GetCurrentToken() // never nil: the token stream ends in EOF
			err = fmt.Errorf("line %d:%d: syntax error at %q", tok.GetLine(), tok.GetColumn(), tok.GetText())
		}
	}()
	return entry(p), nil
}

func shiftError(err error, line int) error {
	if line <= 1 {
		return err
	}
	return fmt.Errorf("from line %d: %w", line, err)
}

// runeOffsets maps the rune indexes ANTLR counts in to byte offsets of text. The extra last entry
// is the length of text.
func runeOffsets(text string) []int {
	out := make([]int, 0, len(text)+1)
	for i := range text {
		out = append(out, i)
	}
	return append(out, len(text))
}

type converter struct {
	rules, symbols []string
	bytes          []int
	base, line     int
	inlined        map[string]string
}

// offset is the offset in the file of a rune index. Only trees read without an error are converted,
// so no token is one error recovery made up, and every index is from 0 to the number of runes.
func (c converter) offset(rune int) int {
	return c.base + c.bytes[rune]
}

// node converts a parse tree, whose nodes are all tokens or rule contexts: ANTLR builds no other.
func (c converter) node(t antlr.Tree, parent *Node) *Node {
	if term, ok := t.(antlr.TerminalNode); ok {
		tok := term.GetSymbol()
		n := &Node{Text: tok.GetText(), Line: c.line + tok.GetLine(), Parent: parent,
			Start: c.offset(tok.GetStart()), End: c.offset(tok.GetStop() + 1)}
		n.Token = c.tokenName(tok.GetTokenType())
		if tok.GetTokenType() == antlr.TokenEOF {
			n.Text = ""
			n.End = n.Start
		}
		return n
	}
	rc := t.(antlr.ParserRuleContext)
	n := &Node{Rule: c.rules[rc.GetRuleIndex()], Parent: parent}
	if s := rc.GetStart(); s != nil {
		n.Line = c.line + s.GetLine()
		n.Start = c.offset(s.GetStart())
	}
	if s := rc.GetStop(); s != nil && s.GetTokenType() != antlr.TokenEOF {
		n.End = c.offset(s.GetStop() + 1)
	} else {
		n.End = n.Start
	}
	for i := 0; i < rc.GetChildCount(); i++ {
		n.Children = append(n.Children, c.node(rc.GetChild(i), n))
	}
	if child, ok := c.inlined[n.Rule]; ok && len(n.Children) == 1 && n.Children[0].Rule == child {
		n.Children = n.Children[0].Children
		for _, m := range n.Children {
			m.Parent = n
		}
	}
	return n
}

// tokenName is the symbolic name of a token type. The grammars here define every token in their
// lexer, so every type but EOF has one.
func (c converter) tokenName(typ int) string {
	if typ == antlr.TokenEOF {
		return "EOF"
	}
	return c.symbols[typ]
}
