func analyze(t *testing.T, c config.Analysis, files map[string]string) *facts.Analysis {
	t.Helper()
	tree := fstest.MapFS{}
	var paths []string
	for p, src := range files {
		tree[p] = &fstest.MapFile{Data: []byte(src)}
		claimed := ansible.Adapter{}.ClaimsConfigured(c, p)
		if claimed {
			paths = append(paths, p)
		}
	}
	sort.Strings(paths)
	a, err := ansible.Adapter{}.Analyze(reuse.Lone(tree), c, paths)
	if err != nil {
		t.Fatal(err)
	}
	return a
}

// viewpoint: behaviour
// target: ansible.Adapter.Claims
// Only YAML in Ansible's layout is Ansible's: CI settings, hadome's own configuration and a role's
// templates and files are not, and neither is a playbook outside the layout unless files.ansible
// names it.
func TestAnsibleClaimsItsLayout(t *testing.T) {
	c := config.Analysis{AnsibleFiles: []string{"deploy/*.yml"}}
	for p, want := range map[string]bool{
		"roles/web/tasks/main.yml": true, "roles/web/handlers/main.yaml": true, "roles/web/defaults/main.yml": true,
		"roles/web/vars/main.yml": true, "roles/web/meta/main.yml": true, "ansible/roles/db/tasks/install.yml": true,
		"playbooks/web.yml": true, "playbooks/group/db.yml": true, "site.yml": true, "playbook.yml": true,
		"molecule/default/verify.yml": true, "roles/web/molecule/default/converge.yml": true,
		"roles/web/templates/app.yml": false, "roles/web/files/seed.yml": false, "roles/web/tasks/main.j2": false,
		".github/workflows/ci.yml": false, ".hadome.yml": false, "docker-compose.yml": false, "ops/site.yml": false,
		"deploy/web.yml": false,
	} {
		got := ansible.Adapter{}.Claims(p)
		if got != want {
			t.Errorf("Claims(%s) = %v, want %v", p, got, want)
		}
	}
	listed := ansible.Adapter{}.ClaimsConfigured(c, "deploy/web.yml")
	if !listed {
		t.Error("a playbook files.ansible names is not claimed")
	}
	other := ansible.Adapter{}.ClaimsConfigured(c, "deploy/web/extra.yml")
	if other {
		t.Error("a file files.ansible does not name is claimed")
	}
}

// viewpoint: behaviour
// target: ansible.Adapter.Analyze
// A role's files have the role as their unit, a playbook its directory, a scenario's files are tests;
// a file that is not YAML is unread and gives nothing else, not even the test a scenario's
// verify.yml would be.
func TestAnsibleFilesAndRoles(t *testing.T) {
	a := analyze(t, config.Analysis{AnsibleFiles: []string{"deploy/*.yml"}, GeneratedFiles: []string{"roles/gen/**"}}, map[string]string{
		"roles/web/tasks/main.yml":              "- name: Install\n  ansible.builtin.package:\n    name: nginx\n",
		"roles/web/defaults/main.yml":           "web_port: 80\n",
		"roles/web/vars/broken.yml":             "a: [\n",
		"roles/gen/defaults/main.yml":           "gen_value: 1\n",
		"roles/db/defaults/main.yml":            "# Code generated by a tool. DO NOT EDIT.\ndb_port: 5432\n",
		"playbooks/web.yml":                     "- hosts: web\n  roles:\n    - web\n",
		"site.yml":                              "- import_playbook: playbooks/web.yml\n",
		"deploy/web.yml":                        "- hosts: web\n",
		"roles/web/molecule/default/verify.yml": "- hosts: all\n",
		"roles/web/molecule/broken/verify.yml":  "- hosts: [\n",
	})
	var got []string
	for _, f := range a.Files {
		got = append(got, fmt.Sprintf("%s %s %s unit=%s path=%s unread=%v lines=%d", f.Path, f.Language, f.Role, f.Unit, f.UnitPath, f.Unread, f.Lines))
	}
	want := []string{
		"deploy/web.yml ansible source unit=deploy path=deploy unread=false lines=1",
		"playbooks/web.yml ansible source unit=playbooks path=playbooks unread=false lines=3",
		"roles/db/defaults/main.yml ansible generated unit=db path=roles/db unread=false lines=2",
		"roles/gen/defaults/main.yml ansible generated unit=gen path=roles/gen unread=false lines=1",
		"roles/web/defaults/main.yml ansible source unit=web path=roles/web unread=false lines=1",
		"roles/web/molecule/broken/verify.yml ansible other unit= path= unread=true lines=1",
		"roles/web/molecule/default/verify.yml ansible test unit=roles/web/molecule/default path=roles/web/molecule/default unread=false lines=1",
		"roles/web/tasks/main.yml ansible source unit=web path=roles/web unread=false lines=3",
		"roles/web/vars/broken.yml ansible other unit= path= unread=true lines=1",
		"site.yml ansible source unit=. path=. unread=false lines=1",
	}
	sort.Strings(got)
	if !slices.Equal(got, want) {
		t.Errorf("files:\n got %q\nwant %q", got, want)
	}
	var ids []string
	for _, s := range a.Symbols {
		ids = append(ids, s.ID)
	}
	if want := []string{"web.web_port"}; !slices.Equal(ids, want) {
		t.Errorf("symbols of source files: got %v, want %v", ids, want)
	}
	var tests []string
	for _, ts := range a.Tests {
		tests = append(tests, ts.Path)
	}
	if want := []string{"roles/web/molecule/default/verify.yml"}; !slices.Equal(tests, want) {
		t.Errorf("tests: got %v, want %v", tests, want)
	}
}

// viewpoint: behaviour
// target: ansible.Adapter.Analyze
// The variables of a role's defaults are its symbols, of kind value: exported unless the name starts
// with _, and documented only by a description in meta/argument_specs.yml that says something.
func TestAnsibleDefaultsAreValues(t *testing.T) {
	a := analyze(t, config.Analysis{}, map[string]string{
		"roles/web/defaults/main.yml": `---
web_port: 80
web_user: www
web_sites:
  - a
  - b
_web_cache: /tmp
`,
		"roles/web/defaults/other.yml": "web_ignored: 1\n",
		"roles/web/vars/main.yml":      "web_internal: 1\n",
		"roles/web/meta/argument_specs.yml": `argument_specs:
  main:
    options:
      web_port:
        type: int
        description: The port the server listens on.
      web_user:
        description: ""
  sites:
    options:
      web_sites:
        description:
          - The sites to serve.
`,
	})
	var got []string
	for _, s := range a.Symbols {
		got = append(got, fmt.Sprintf("%s %s %d-%d exported=%v doc=%v", s.ID, s.Kind, s.Line, s.EndLine, s.Exported, s.Doc))
	}
	want := []string{
		"web._web_cache value 7-7 exported=false doc=false",
		"web.web_port value 2-2 exported=true doc=true",
		"web.web_sites value 4-6 exported=true doc=true",
		"web.web_user value 3-3 exported=true doc=false",
	}
	sort.Strings(got)
	if !slices.Equal(got, want) {
		t.Errorf("symbols:\n got %q\nwant %q", got, want)
	}
}

// viewpoint: behaviour
// target: ansible.Adapter.Analyze
// A role's dependencies, a play's roles and include_role and import_role tasks, inside blocks too, are
// imports. A role of the repository is internal and is its unit; any other is named by its collection
// or as written; a templated name is unknown. Configuration's rules.tests.io marks input and output.
func TestAnsibleImports(t *testing.T) {
	a := analyze(t, config.Analysis{IO: []string{"community.general"}}, map[string]string{
		"roles/db/tasks/main.yml": "- name: Install\n  ansible.builtin.package:\n    name: postgresql\n",
		"roles/web/meta/main.yml": `dependencies:
  - db
  - role: geerlingguy.nginx
`,
		"roles/web/tasks/main.yml": `- name: Firewall
  ansible.builtin.include_role:
    name: community.general.ufw
- name: Steps
  block:
    - import_role:
        name: db
  rescue:
    - include_role:
        name: "{{ fallback_role }}"
`,
		"playbooks/site.yml": `- hosts: web
  roles:
    - web
    - { role: db, tags: [db] }
  post_tasks:
    - ansible.builtin.import_role:
        name: ops.tools.monitor
`,
	})
	var got []string
	for _, im := range a.Imports {
		got = append(got, fmt.Sprintf("%s:%d %s -> %s internal=%v io=%v unknown=%v text=%s", im.Path, im.Line, im.FromUnit, im.ToUnit,
			im.Internal, im.IO, im.Unknown, im.Text))
	}
	want := []string{
		"playbooks/site.yml:3 playbooks -> web internal=true io=false unknown=false text=web",
		"playbooks/site.yml:4 playbooks -> db internal=true io=false unknown=false text=db",
		"playbooks/site.yml:7 playbooks -> ops.tools internal=false io=false unknown=false text=ops.tools.monitor",
		"roles/web/meta/main.yml:2 web -> db internal=true io=false unknown=false text=db",
		"roles/web/meta/main.yml:3 web -> geerlingguy.nginx internal=false io=false unknown=false text=geerlingguy.nginx",
		"roles/web/tasks/main.yml:3 web -> community.general internal=false io=true unknown=false text=community.general.ufw",
		"roles/web/tasks/main.yml:7 web -> db internal=true io=false unknown=false text=db",
		"roles/web/tasks/main.yml:10 web ->  internal=false io=false unknown=true text={{ fallback_role }}",
	}
	sort.Slice(got, func(i, j int) bool { return got[i] < got[j] })
	sort.Strings(want)
	if !slices.Equal(got, want) {
		t.Errorf("imports:\n got %q\nwant %q", got, want)
	}
}

const verify = `---
# Checks that the server is installed and answers.
# guards: web-serves
- name: Verify
  hosts: all
  tasks:
    - name: Collect packages
      ansible.builtin.package_facts:
    - ansible.builtin.assert:
        that: "'nginx' in ansible_facts.packages"
    - name: Wait for the server
      ansible.builtin.pause:
        seconds: 5
    - block:
        - name: Ask it
          ansible.builtin.uri:
            url: http://localhost
          register: page
          failed_when: page.status != 200
        - assert:
            that: page.status == 200
`

// viewpoint: behaviour
// target: ansible.Adapter.Analyze
// Each scenario's verify playbook is a test named after the scenario: its assert tasks and tasks with
// failed_when are its asserts, a pause is a sleep, and the repository's roles its converge playbook
// applies are its calls; a templated role is a call hadome cannot identify.
func TestAnsibleScenariosAreTests(t *testing.T) {
	a := analyze(t, config.Analysis{}, map[string]string{
		"roles/web/tasks/main.yml":              "- name: Install\n  ansible.builtin.package:\n    name: nginx\n",
		"roles/db/tasks/main.yml":               "- name: Install\n  ansible.builtin.package:\n    name: postgresql\n",
		"roles/web/molecule/default/verify.yml": verify,
		"roles/web/molecule/default/converge.yml": `- hosts: all
  roles:
    - db
    - community.general.ufw
  tasks:
    - ansible.builtin.include_role:
        name: web
    - include_role:
        name: web
    - include_role:
        name: "{{ lookup('env', 'ROLE') }}"
`,
		"roles/web/molecule/default/molecule.yml": "driver:\n  name: docker\n",
		"molecule/empty/verify.yml":               "- hosts: all\n  tasks: []\n",
	})
	if len(a.Tests) != 2 {
		t.Fatalf("got %d tests, want 2", len(a.Tests))
	}
	sort.Slice(a.Tests, func(i, j int) bool { return a.Tests[i].Path < a.Tests[j].Path })
	empty, web := a.Tests[0], a.Tests[1]
	sum := func(tt facts.Test) string {
		var calls, hazards []string
		for _, c := range tt.Calls {
			calls = append(calls, fmt.Sprintf("%s x%d", c.Target, c.Times))
		}
		for _, h := range tt.Hazards {
			hazards = append(hazards, fmt.Sprintf("%s %d %s", h.Category, h.Line, h.Evidence))
		}
		return fmt.Sprintf("%s line=%d asserts=%d unresolved=%d calls=%v hazards=%v", tt.Name, tt.Line, tt.Asserts, tt.Unresolved, calls, hazards)
	}
	if got, want := sum(web), "default line=4 asserts=3 unresolved=1 calls=[db x1 web x2] hazards=[sleep 12 ansible.builtin.pause: seconds: 5]"; got != want {
		t.Errorf("web's scenario:\n got %s\nwant %s", got, want)
	}
	if got, want := sum(empty), "empty line=1 asserts=0 unresolved=0 calls=[] hazards=[]"; got != want {
		t.Errorf("an empty scenario:\n got %s\nwant %s", got, want)
	}
	if got := web.Declared["guards"]; !slices.Equal(got, []string{"web-serves"}) {
		t.Errorf("declared guards = %v, want [web-serves]", got)
	}
	if empty.Declared != nil {
		t.Errorf("a verify playbook with no comment declared %v", empty.Declared)
	}
}

// viewpoint: invariant
// target: ansible.Adapter.Analyze
// Adapters design invariant 6: a verify playbook's fingerprint ignores its comments and layout, and
// changes with any literal.
func TestAnsibleVerifyFingerprint(t *testing.T) {
	body := func(src string) string {
		a := analyze(t, config.Analysis{}, map[string]string{"molecule/default/verify.yml": src})
		if len(a.Tests) != 1 || a.Tests[0].Body == "" {
			t.Fatalf("no fingerprint from %q", src)
		}
		return a.Tests[0].Body
	}
	base := body("- hosts: all\n  tasks:\n    - assert:\n        that: x == 1\n")
	same := body("# a comment\n- hosts:   all\n  tasks:\n\n    - assert: # another\n        that:   x == 1\n")
	other := body("- hosts: all\n  tasks:\n    - assert:\n        that: x == 2\n")
	if base != same {
		t.Error("commenting or re-laying out a verify playbook changed its fingerprint")
	}
	if base == other {
		t.Error("changing a literal kept the fingerprint")
	}
}

// viewpoint: behaviour
// target: ansible.Adapter.Analyze
// # comments are comments, without the #; ansible-lint's noqa and yamllint's instructions are
// directives, and an exception marker stays an ordinary comment for the engine.
func TestAnsibleComments(t *testing.T) {
	a := analyze(t, config.Analysis{}, map[string]string{"roles/web/tasks/main.yml": `# yamllint disable rule:line-length
- name: Install # noqa: package-latest
  ansible.builtin.package:
    name: nginx
    state: latest
# gate:allow tests/scope-shrunk the role is retired
- ansible.builtin.command: echo hi # noqa
`})
	var got []string
	for _, c := range a.Comments {
		got = append(got, fmt.Sprintf("%d %q directive=%v", c.Line, c.Text, c.Directive))
	}
	want := []string{
		`1 "yamllint disable rule:line-length" directive=true`,
		`2 "noqa: package-latest" directive=true`,
		`6 "gate:allow tests/scope-shrunk the role is retired" directive=false`,
		`7 "noqa" directive=true`,
	}
	if !slices.Equal(got, want) {
		t.Errorf("comments:\n got %q\nwant %q", got, want)
	}
}

// viewpoint: behaviour
// target: ansible.Adapter.Analyze
// Molecule sets MOLECULE_PROJECT_DIRECTORY to the role a scenario is inside, so a scenario under
// roles/<role>/molecule that names the role by that variable's base name calls the role. Outside a
// role the same expression stays unidentified, and so does any other template.
func TestAnsibleMoleculeProjectDirectoryNamesTheRole(t *testing.T) {
	converge := func(names ...string) string {
		src := "- hosts: all\n  tasks:\n"
		for _, n := range names {
			src += "    - ansible.builtin.include_role:\n        name: " + n + "\n"
		}
		return src
	}
	const plain = `"{{ lookup('env', 'MOLECULE_PROJECT_DIRECTORY') | basename }}"`
	const spaced = `'{{lookup("ansible.builtin.env","MOLECULE_PROJECT_DIRECTORY")|basename}}'`
	const other = `"{{ lookup('env', 'ROLE') | basename }}"`
	a := analyze(t, config.Analysis{}, map[string]string{
		"roles/web/tasks/main.yml":                "- name: Install\n  ansible.builtin.package:\n    name: nginx\n",
		"roles/web/molecule/default/converge.yml": converge(plain, spaced, other),
		"roles/web/molecule/default/verify.yml":   "- hosts: all\n",
		"molecule/default/converge.yml":           converge(plain),
		"molecule/default/verify.yml":             "- hosts: all\n",
	})
	var got []string
	for _, tt := range a.Tests {
		var calls []string
		for _, c := range tt.Calls {
			calls = append(calls, fmt.Sprintf("%s x%d", c.Target, c.Times))
		}
		got = append(got, fmt.Sprintf("%s calls=%v unresolved=%d", tt.Path, calls, tt.Unresolved))
	}
	sort.Strings(got)
	want := []string{
		"molecule/default/verify.yml calls=[] unresolved=1",
		"roles/web/molecule/default/verify.yml calls=[web x2] unresolved=1",
	}
	if !slices.Equal(got, want) {
		t.Errorf("tests:\n got %q\nwant %q", got, want)
	}
}
