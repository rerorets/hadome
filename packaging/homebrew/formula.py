"""Writes the Homebrew formula of one release to standard output.

    python3 formula.py <version> <SHA256SUMS>

The formula goes to the rerorets/homebrew-tap repository as Formula/hadome.rb. Homebrew checks each
download against the SHA-256 written here, which comes from the release's own SHA256SUMS.
"""

import sys

TEMPLATE = '''# Generated by packaging/homebrew/formula.py for hadome {version}. Do not edit by hand.
class Hadome < Formula
  desc "Reports the violations a change adds and the tests it weakens"
  homepage "https://github.com/rerorets/hadome"
  version "{version}"
  license "MIT"

  on_macos do
    on_arm do
      url "{base}/hadome_{version}_darwin_arm64.tar.gz"
      sha256 "{darwin_arm64}"
    end
    on_intel do
      url "{base}/hadome_{version}_darwin_amd64.tar.gz"
      sha256 "{darwin_amd64}"
    end
  end

  on_linux do
    on_arm do
      url "{base}/hadome_{version}_linux_arm64.tar.gz"
      sha256 "{linux_arm64}"
    end
    on_intel do
      url "{base}/hadome_{version}_linux_amd64.tar.gz"
      sha256 "{linux_amd64}"
    end
  end

  def install
    bin.install "hadome"
    prefix.install "LICENSE", "THIRD_PARTY_NOTICES"
  end

  test do
    assert_match version.to_s, shell_output("#{{bin}}/hadome version")
  end
end
'''


def main():
    """Prints the formula, failing when SHA256SUMS lacks a platform Homebrew installs."""
    if len(sys.argv) != 3:
        sys.exit("usage: python3 formula.py <version> <SHA256SUMS>")
    version, sums = sys.argv[1:]
    digests = {}
    for line in open(sums):
        digest, name = line.split()
        for platform in ("darwin_arm64", "darwin_amd64", "linux_arm64", "linux_amd64"):
            if name.lstrip("*") == f"hadome_{version}_{platform}.tar.gz":
                digests[platform] = digest
    missing = {"darwin_arm64", "darwin_amd64", "linux_arm64", "linux_amd64"} - digests.keys()
    if missing:
        sys.exit(f"SHA256SUMS lacks {', '.join(sorted(missing))}")
    base = f"https://github.com/rerorets/hadome/releases/download/v{version}"
    sys.stdout.write(TEMPLATE.format(version=version, base=base, **digests))


if __name__ == "__main__":
    main()
